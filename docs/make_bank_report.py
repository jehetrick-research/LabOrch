"""Write docs/bank_v2.md and docs/img/sustain_examples.png from Bank v2.

    python docs/make_bank_report.py

Needs matplotlib; the spreadsheet comparison needs openpyxl and
Soundbank_McGill/ForJim-04-08-20 (not in the public repo), and the figure
needs the McGill audio. Missing pieces are skipped.
"""
import collections
import sys
from pathlib import Path

import numpy as np

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT))
from laborch import Bank, config                                   # noqa: E402
from laborch.metadata import FAMILIES, INSTRUMENT_NAMES, MODE_NAMES, ranges, spreadsheet_names  # noqa: E402

OUT = ROOT / "docs" / "bank_v2.md"
FIG = ROOT / "docs" / "img" / "sustain_examples.png"
EXAMPLES = ["flu-c7-ord-mf", "ctb-a1o-mtd-mf", "vln-a4x-ord-mf", "trb-f2-ord-mf",
            "vib-e4-bwd-mf", "mrb-c4-ord-mf", "pno-c4-ord-ff", "cro-cs6-bbt-mf"]


def pct(a, q):
    return np.percentile(np.asarray(a, float), q)


def figure(bank):
    import matplotlib
    matplotlib.use("Agg")
    import matplotlib.pyplot as plt
    from laborch.spectra import frame_power, load_float, _db
    fig, axes = plt.subplots(4, 2, figsize=(10, 9), sharey=True)
    for ax, n in zip(axes.flat, EXAMPLES):
        r = bank.meta[n]
        _, ms = frame_power(load_float(bank.sound_path(n)))
        t = (np.arange(len(ms)) * config.HOP + config.NFFT / 2) / config.SAMPLE_RATE
        e = _db(ms)
        ax.plot(t, e - e.max(), lw=1, color="#333")
        ax.axvspan(r["sustain_start_s"], r["sustain_end_s"], color="#4a90d9", alpha=0.25)
        ax.set_title(f"{n}  ({r['method']})", fontsize=9)
        ax.set_ylim(-45, 3)
        ax.grid(alpha=0.3)
    for ax in axes[-1]:
        ax.set_xlabel("time (s)")
    for ax in axes[:, 0]:
        ax.set_ylabel("level (dB re peak)")
    fig.suptitle("Bank v2: frame level and the region averaged (shaded)")
    fig.tight_layout()
    FIG.parent.mkdir(parents=True, exist_ok=True)
    fig.savefig(FIG, dpi=110)


def main():
    bank = Bank.load()
    rows = [bank.meta[n] for n in bank.names]
    L = []
    w = L.append
    w("# Bank v2: analysis and coverage report\n")
    w("Generated by `docs/make_bank_report.py` from "
      "`Soundbank_McGill/Bank_v2/bank_v2.npz` and `bank_v2.csv`.\n")

    # ---- analysis -------------------------------------------------------
    w("## How the spectra were made\n")
    w("Each McGill recording (44.1 kHz, mixed to mono, scaled to -1..1) is cut into "
      "4,096-sample Hamming frames at hop 512. Each frame's power spectrum "
      "|X_k|^2 is scaled so its sum is the frame's mean square (Parseval). "
      "The Bank spectrum is the mean over the analysed region, so "
      "`10*log10(sum)` is the region's level in dBFS.\n")
    w("- **Sustained sounds** (bowed, blown, bowed vibraphone): the frame level is "
      f"smoothed over {config.SMOOTH_FRAMES} frames (about 0.2 s); the reference is the "
      f"median of frames within {config.LOUD_DB:.0f} dB of the smoothed peak; the region is "
      f"the longest run within ±{config.SUSTAIN_DB:.0f} dB of it, less {config.EDGE_FRAMES} "
      "frames at each end.")
    w("- **Decaying sounds** (piano, marimba, xylophone, glockenspiel, crotales, tubular "
      f"bells, hard-mallet vibraphone): from the loudest frame until {config.DECAY_DB:.0f} dB "
      f"below it, at most {config.DECAY_MAX_S} s.")
    w(f"- Fallback: the v1 fixed {config.SHAVE:.0%} trim when fewer than "
      f"{config.MIN_FRAMES} frames qualify.\n")
    meth = collections.Counter((r["envelope"], r["method"]) for r in rows)
    w("| Envelope | Method | Sounds | Region / note length (5th, 50th, 95th pct) | "
      "Region length, s | Similarity to v1 (1st, 5th, 50th pct) |")
    w("| --- | --- | --- | --- | --- | --- |")
    for (env, m), c in sorted(meth.items()):
        rr = [r for r in rows if r["envelope"] == env and r["method"] == m]
        frac = [(r["sustain_end_s"] - r["sustain_start_s"]) / r["duration_s"] for r in rr]
        dur = [r["sustain_end_s"] - r["sustain_start_s"] for r in rr]
        sim = [r["similarity_v1"] for r in rr]
        w(f"| {env} | {m} | {c} | {', '.join(f'{v:.2f}' for v in pct(frac, [5, 50, 95]))} | "
          f"{', '.join(f'{v:.2f}' for v in pct(dur, [5, 50, 95]))} | "
          f"{', '.join(f'{v:.3f}' for v in pct(sim, [1, 5, 50]))} |")
    w("\n*Similarity to v1* is the cosine between sqrt(v2 power) and the v1 FFTBank "
      "magnitude spectrum of the same sound. Sustained sounds barely change; decaying "
      "sounds change more because v1 averaged the middle 70% of the whole ring-out.\n")
    low = sorted((r for r in rows if r["envelope"] == "sustained"),
                 key=lambda r: r["similarity_v1"])[:8]
    w("Sustained sounds that changed most: " +
      ", ".join(f"`{r['name']}` ({r['similarity_v1']:.3f})" for r in low) + ".\n")
    if FIG.exists() or _try(figure, bank):
        w("![Frame level and analysed region for eight sounds](img/sustain_examples.png)\n")

    # ---- levels ---------------------------------------------------------
    w("## Levels\n")
    w("Spectra keep the recorded level. Median level by instrument (dBFS, "
      "quietest first):\n")
    lv = collections.defaultdict(list)
    for r in rows:
        lv[r["instrument"]].append(r["level_db"])
    w(", ".join(f"{k} {np.median(v):.0f}" for k, v in
                sorted(lv.items(), key=lambda kv: np.median(kv[1]))) + "\n")
    d = []
    for r in rows:
        if r["instrument"] == "pno" and r["dynamic"] == "ff":
            pp = r["name"].replace("-ff", "-pp")
            if pp in bank.meta:
                d.append(r["level_db"] - bank.meta[pp]["level_db"])
    if d:
        w(f"**Recorded level is not playing level.** For the {len(d)} piano notes recorded "
          f"at both pp and ff, ff is a median {np.median(d):+.1f} dB relative to pp "
          f"(10th-90th percentile {pct(d, 10):+.1f} to {pct(d, 90):+.1f} dB): the MUMS "
          "tracks were evidently gain-adjusted. Bank levels describe the recordings, not "
          "the instruments; a loudness model (or calibrated recordings) is needed before "
          "weights can be read as dynamics. `Bank.load(normalize='unit')` gives "
          "level-free spectra.\n")

    # ---- coverage -------------------------------------------------------
    w("## Coverage\n")
    w(f"{len(rows)} sounds, {len(bank.instruments)} instruments.\n")
    w("| Family | Instrument | Mode | Sounds | Range (MIDI) | Range |")
    w("| --- | --- | --- | --- | --- | --- |")
    rg = ranges(rows)
    cnt = collections.Counter((r["instrument"], r["mode"]) for r in rows)
    pname = {r["midi"]: r["pitch"] for r in rows}
    for fam, insts in FAMILIES.items():
        for i in insts:
            for (inst, mode), (lo, hi) in sorted(rg.items()):
                if inst == i:
                    w(f"| {fam} | {INSTRUMENT_NAMES[i]} ({i}) | {MODE_NAMES.get(mode, mode)} "
                      f"({mode}) | {cnt[(inst, mode)]} | {lo}-{hi} | {pname[lo]}-{pname[hi]} |")
    dyn = collections.Counter(r["dynamic"] for r in rows)
    w(f"\nDynamics: {dict(dyn)}. Only piano has pp and ff.\n")
    w("### Gaps\n")
    try:
        sheet = set(spreadsheet_names())
        missing = sorted(sheet - set(bank.names) - {"tpt-fs3-hmo-mf"})
        extra = sorted(set(bank.names) - sheet - {"tpc-fs3-hmo-mf"})
        w(f"- François' spreadsheets list {len(sheet)} sounds. Missing from the Bank: "
          f"{len(missing)}" + (f" ({_summ(missing)})" if missing else "") + ".")
        if extra:
            w(f"- In the Bank but not the spreadsheets: {', '.join(extra)}.")
        w("- `tpt-fs3-hmo-mf` in the spreadsheet and the recording's file name is a typo "
          "for `tpc-fs3-hmo-mf` (handled by `laborch.build.NAME_FIXES`).")
    except Exception as e:  # spreadsheets or openpyxl not available
        w(f"- (spreadsheet comparison skipped: {e.__class__.__name__})")
    thin = sorted((c, i) for i, c in collections.Counter(r["instrument"] for r in rows).items() if c < 13)
    w("- Thin instruments: " + ", ".join(f"{INSTRUMENT_NAMES[i]} {c}" for c, i in thin) + ".")
    w("- Dynamics: strings, winds, brass and percussion are mf only.")
    w("- Modes not recorded: e.g. string pizzicato and sul ponticello, flutter-tongue, "
      "wind multiphonics (some trumpet mutes and bassoon multiphonics are in MiscSounds "
      "as Targets).\n")
    OUT.write_text("\n".join(L) + "\n", encoding="utf-8")
    print("wrote", OUT)


def _summ(names):
    by = collections.Counter(n.split("-")[0] for n in names)
    return ", ".join(f"{INSTRUMENT_NAMES.get(i, i)} {c}" for i, c in by.items())


def _try(f, *a):
    try:
        f(*a)
        return True
    except Exception as e:
        print("figure skipped:", e)
        return False


if __name__ == "__main__":
    main()
